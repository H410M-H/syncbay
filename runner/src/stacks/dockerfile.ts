/**
 * Dockerfile generation for detected stacks. Pure: returns text, writes nothing.
 *
 * Every image listens on `$PORT` (default baked in with `ENV PORT`, overridden by the runner's
 * `docker run -e PORT`) on all interfaces (`HOST=0.0.0.0`). Only Docker Hub images are used, with
 * multi-stage builds where the runtime image can drop the toolchain. Build steps honour the
 * predefined HTTP(S)_PROXY / NO_PROXY build args, and with `extraCaCert` they trust
 * `syncbay-build-ca.crt` (a corporate or egress-proxy CA copied into the context by the runner).
 */

import { BUILD_CA_FILE, type DetectedStack, type DockerfileOptions, type StackPlan } from "./types.ts";

const CA_PATH = `/usr/local/share/ca-certificates/${BUILD_CA_FILE}`;
const CA_BUNDLE = "/usr/local/share/syncbay/ca-bundle.crt";

/** Lines that make one build stage trust the extra CA (system store + the env vars tools read). */
function caBlock(opts: DockerfileOptions, java = false): string[] {
  if (!opts.extraCaCert) return [];
  const lines = [
    `COPY ${BUILD_CA_FILE} ${CA_PATH}`,
    `RUN set -e; mkdir -p /usr/local/share/syncbay; { cat /etc/ssl/certs/ca-certificates.crt 2>/dev/null || true; echo; cat ${CA_PATH}; } > ${CA_BUNDLE}; (update-ca-certificates >/dev/null 2>&1 || true)`,
    `ENV NODE_EXTRA_CA_CERTS=${CA_PATH} SSL_CERT_FILE=${CA_BUNDLE} PIP_CERT=${CA_BUNDLE} REQUESTS_CA_BUNDLE=${CA_BUNDLE} CURL_CA_BUNDLE=${CA_BUNDLE} CARGO_HTTP_CAINFO=${CA_BUNDLE} GIT_SSL_CAINFO=${CA_BUNDLE} BUNDLE_SSL_CA_CERT=${CA_BUNDLE} DENO_CERT=${CA_BUNDLE}`,
  ];
  if (java) {
    // keytool imports one certificate per call: split the file and import each into the JDK store.
    lines.push(
      `RUN set -e; awk 'BEGIN{n=0} /BEGIN CERTIFICATE/{n++} n{print > ("/tmp/sbca-" n ".pem")}' ${CA_PATH}; i=0; for c in /tmp/sbca-*.pem; do i=$((i+1)); keytool -importcert -noprompt -cacerts -storepass changeit -alias "syncbay-build-ca-$i" -file "$c" >/dev/null 2>&1 || true; done; rm -f /tmp/sbca-*.pem`
    );
  }
  return lines;
}

/** Shell prefix that turns HTTPS_PROXY / NO_PROXY into JVM proxy flags (Maven and Gradle ignore the env vars). */
const JVM_PROXY =
  `JP=""; for v in "$HTTPS_PROXY" "$https_proxy" "$HTTP_PROXY" "$http_proxy"; do if [ -n "$v" ]; then h=\${v#*://}; h=\${h##*@}; h=\${h%%/*}; JP="-Dhttps.proxyHost=\${h%:*} -Dhttps.proxyPort=\${h##*:} -Dhttp.proxyHost=\${h%:*} -Dhttp.proxyPort=\${h##*:}"; break; fi; done; ` +
  `NP="\${NO_PROXY:-$no_proxy}"; if [ -n "$JP" ] && [ -n "$NP" ]; then JP="$JP -Dhttp.nonProxyHosts=$(printf %s "$NP" | tr ',' '|')"; fi; export MAVEN_OPTS="$MAVEN_OPTS $JP" GRADLE_OPTS="$GRADLE_OPTS $JP"; `;

/** `RUN` with a user-supplied command, in exec form so it cannot break the Dockerfile syntax. */
const runUser = (command: string) => `RUN ["/bin/sh", "-c", ${JSON.stringify(command)}]`;

/** `CMD` that runs `start` through a shell (so `$PORT` expands) and execs it when it is a single command. */
function cmd(start?: string): string {
  const command = start?.trim() || `echo "No start command for this service: set one in the service settings" >&2; exit 1`;
  const body = /[;&|\n]/.test(command) ? command : `exec ${command}`;
  return `CMD ["sh", "-c", ${JSON.stringify(body)}]`;
}

const portEnv = (port: number, extra = "") => [`ENV PORT=${port} HOST=0.0.0.0${extra ? ` ${extra}` : ""}`, `EXPOSE ${port}`];

const header = (stack: DetectedStack) => [
  `# Generated by Syncbay for ${stack.label}${stack.framework ? ` (${stack.framework})` : ""}, detected from ${stack.reason}.`,
  `# Add your own Dockerfile (or set SYNCBAY_BUILDER) to replace it. Regenerated on every build.`,
];

// ─── NODE / BUN ──────────────────────────────────────────────────────────────

const NODE_ENV_LINE = "ENV NEXT_TELEMETRY_DISABLED=1 NUXT_TELEMETRY_DISABLED=1 ASTRO_TELEMETRY_DISABLED=1 npm_config_update_notifier=false npm_config_fund=false npm_config_audit=false";

function nodeImage(plan: StackPlan, opts: DockerfileOptions): string {
  if (plan.packageManager === "bun") return "oven/bun:1";
  const major = /^\d+$/.test(opts.nodeMajor || "") ? opts.nodeMajor : plan.nodeMajor || "22";
  return `node:${major}-bookworm-slim`;
}

function nodeInstall(plan: StackPlan): string[] {
  switch (plan.packageManager) {
    case undefined:
      return [];
    case "pnpm":
      return [
        `RUN npm install -g pnpm@${plan.pnpmVersion || "10"} --no-audit --no-fund`,
        `RUN if [ -f pnpm-lock.yaml ]; then pnpm install --frozen-lockfile --prod=false; else pnpm install --prod=false; fi`,
      ];
    case "yarn":
      return [`RUN if [ -f yarn.lock ]; then yarn install --frozen-lockfile --production=false; else yarn install --production=false; fi`];
    case "yarn-berry":
      return [`RUN corepack enable && if [ -f yarn.lock ]; then yarn install --immutable; else yarn install; fi`];
    case "bun":
      return [`RUN if [ -f bun.lockb ] || [ -f bun.lock ]; then bun install --frozen-lockfile; else bun install; fi`];
    default:
      return [`RUN if [ -f package-lock.json ] || [ -f npm-shrinkwrap.json ]; then npm ci --include=dev; else npm install --include=dev; fi`];
  }
}

/** Install dependencies (manifests first, so a code-only change reuses the layer), copy the source, build. */
function nodeBuildSteps(stack: DetectedStack, opts: DockerfileOptions): string[] {
  const plan = stack.plan;
  const lines: string[] = [];
  if (plan.packageManager !== "bun") lines.push(NODE_ENV_LINE);
  if (plan.noManifest) {
    // A plain server file with no package.json: nothing to install.
    lines.push("COPY . .");
  } else if (plan.packageManager && !plan.installNeedsSource) {
    lines.push(`COPY package.json package-lock.json* npm-shrinkwrap.json* pnpm-lock.yaml* yarn.lock* bun.lock* bun.lockb* .npmrc* ./`);
    lines.push(...nodeInstall(plan));
    lines.push("COPY . .");
  } else {
    lines.push("COPY . .");
    lines.push(...nodeInstall(plan));
  }
  const build = opts.buildCommand || stack.buildCommand;
  if (build) lines.push(runUser(build));
  return lines;
}

function nodeServer(stack: DetectedStack, opts: DockerfileOptions): string[] {
  return [
    `FROM ${nodeImage(stack.plan, opts)}`,
    "WORKDIR /app",
    ...caBlock(opts),
    ...nodeBuildSteps(stack, opts),
    ...portEnv(opts.port, "HOSTNAME=0.0.0.0 NODE_ENV=production"),
    cmd(opts.startCommand || stack.startCommand),
  ];
}

// ─── STATIC SITES ────────────────────────────────────────────────────────────

/** nginx server block: listen on $PORT (filled in by the image's envsubst templates), SPA fallback to index.html. */
const NGINX_TEMPLATE = [
  "server {",
  "  listen ${PORT};",
  "  server_name _;",
  "  root /usr/share/nginx/html;",
  "  index index.html;",
  "  absolute_redirect off;",
  "  gzip on;",
  "  gzip_types text/plain text/css application/javascript application/json image/svg+xml;",
  "  location / {",
  "    try_files $uri $uri/ /index.html;",
  "  }",
  "  location ~* \\.(?:js|mjs|css|map|woff2?|ttf|png|jpe?g|gif|svg|ico|webp|avif|wasm)$ {",
  "    try_files $uri =404;",
  "    expires 7d;",
  "    access_log off;",
  "  }",
  "}",
];

/** One single-quoted shell word; line breaks are refused (they would end the Dockerfile instruction). */
const shArg = (value: string) => {
  if (/[\r\n\0]/.test(value)) throw new Error(`Refusing a value with a line break in a generated Dockerfile: ${JSON.stringify(value.slice(0, 80))}`);
  return `'${value.replace(/'/g, `'\\''`)}'`;
};

function nginxStage(port: number): string[] {
  return [
    "FROM nginx:1.27-alpine",
    `RUN rm -f /etc/nginx/conf.d/default.conf && mkdir -p /etc/nginx/templates && printf '%s\\n' ${NGINX_TEMPLATE.map(shArg).join(" ")} > /etc/nginx/templates/default.conf.template`,
  ].concat(portEnv(port));
}

function staticSite(stack: DetectedStack, opts: DockerfileOptions): string[] {
  const plan = stack.plan;
  const out = plan.outputDir || ".";
  if (!plan.needsBuild && !opts.buildCommand) {
    return [...nginxStage(opts.port), `COPY ${out === "." ? "." : `${out}/`} /usr/share/nginx/html/`];
  }
  const dirs = [...new Set([out, ...(plan.outputCandidates || ["dist", "build", "out", "public"])])];
  const pick =
    `RUN set -e; mkdir -p /out; for d in ${dirs.map(shArg).join(" ")}; do if [ -f "$d/index.html" ]; then cp -a "$d"/. /out/; echo "Serving $d"; exit 0; fi; done; ` +
    `f=$(find dist build out -maxdepth 3 -name index.html 2>/dev/null | head -n 1); if [ -n "$f" ]; then cp -a "$(dirname "$f")"/. /out/; echo "Serving $(dirname "$f")"; exit 0; fi; ` +
    `echo ${shArg(`The build produced no index.html in ${dirs.join(", ")}; set the output directory in the build command or add a Dockerfile`)} >&2; exit 1`;
  return [
    `FROM ${nodeImage(plan, opts)} AS build`,
    "WORKDIR /app",
    ...caBlock(opts),
    ...nodeBuildSteps(stack, opts),
    pick,
    "",
    ...nginxStage(opts.port),
    "COPY --from=build /out/ /usr/share/nginx/html/",
  ];
}

// ─── PYTHON ──────────────────────────────────────────────────────────────────

function pythonInstall(plan: StackPlan): string[] {
  const extras = plan.pythonExtras || [];
  const pipExtras = extras.length ? ` && pip install ${extras.map(shArg).join(" ")}` : "";
  switch (plan.pythonInstall) {
    case "uv":
      return [
        "ENV UV_PROJECT_ENVIRONMENT=/opt/venv UV_LINK_MODE=copy PATH=/opt/venv/bin:$PATH",
        "COPY pyproject.toml uv.lock* ./",
        `RUN pip install uv && uv sync --frozen --no-dev --no-install-project${extras.length ? ` && uv pip install --python /opt/venv/bin/python ${extras.map(shArg).join(" ")}` : ""}`,
      ];
    case "poetry":
      return [
        "COPY pyproject.toml poetry.lock* ./",
        `RUN pip install poetry && poetry config virtualenvs.create false && poetry install --no-interaction --no-ansi --no-root --only main${pipExtras}`,
      ];
    case "pipenv":
      return ["COPY Pipfile Pipfile.lock* ./", `RUN pip install pipenv && if [ -f Pipfile.lock ]; then pipenv install --system --deploy; else pipenv install --system --skip-lock; fi${pipExtras}`];
    case "pyproject": {
      const deps = [...(plan.pythonDeps || []), ...extras];
      return deps.length ? [`RUN pip install ${deps.map(shArg).join(" ")}`] : [];
    }
    case "requirements":
      return plan.installNeedsSource
        ? [] // requirements.txt includes other files (-r / -e .): installed after the source is copied
        : ["COPY requirements.txt ./", `RUN pip install -r requirements.txt${pipExtras}`];
    default:
      return extras.length ? [`RUN pip install ${extras.map(shArg).join(" ")}`] : [];
  }
}

function python(stack: DetectedStack, opts: DockerfileOptions): string[] {
  const plan = stack.plan;
  const lines = [
    `FROM python:${plan.pythonVersion || "3.12"}-slim`,
    "WORKDIR /app",
    ...caBlock(opts),
    "ENV PYTHONUNBUFFERED=1 PYTHONDONTWRITEBYTECODE=1 PIP_NO_CACHE_DIR=1 PIP_DISABLE_PIP_VERSION_CHECK=1 PIP_ROOT_USER_ACTION=ignore",
  ];
  if (plan.aptPackages?.length) {
    lines.push(`RUN apt-get update && apt-get install -y --no-install-recommends ${plan.aptPackages.join(" ")} && rm -rf /var/lib/apt/lists/*`);
  }
  lines.push(...pythonInstall(plan), "COPY . .");
  if (plan.pythonInstall === "requirements" && plan.installNeedsSource) {
    const extras = plan.pythonExtras || [];
    lines.push(`RUN pip install -r requirements.txt${extras.length ? ` && pip install ${extras.map(shArg).join(" ")}` : ""}`);
  }
  if (stack.framework === "Django") {
    lines.push(`RUN python manage.py collectstatic --noinput >/dev/null 2>&1 && echo "collectstatic done" || echo "collectstatic skipped (set STATIC_ROOT to serve static files)"`);
  }
  if (opts.buildCommand) lines.push(runUser(opts.buildCommand));
  lines.push(...portEnv(opts.port), cmd(opts.startCommand || stack.startCommand));
  return lines;
}

// ─── GO / RUST ───────────────────────────────────────────────────────────────

/** Runtime stage for a static binary: debian-slim plus CA roots and zoneinfo from the builder (no apt). */
const binaryRuntime = (port: number, extraEnv = "") => [
  "FROM debian:bookworm-slim",
  "COPY --from=build /etc/ssl/certs/ca-certificates.crt /etc/ssl/certs/ca-certificates.crt",
  "COPY --from=build /usr/share/zoneinfo /usr/share/zoneinfo",
  "WORKDIR /app",
  ...portEnv(port, extraEnv),
];

function go(stack: DetectedStack, opts: DockerfileOptions): string[] {
  const plan = stack.plan;
  const build = opts.buildCommand
    ? runUser(opts.buildCommand)
    : `RUN go build -trimpath -ldflags="-s -w" -o /out/app ${shArg(plan.goPackage || ".")}`;
  return [
    `FROM golang:${plan.goVersion || "1.23"}-bookworm AS build`,
    "WORKDIR /src",
    ...caBlock(opts),
    `ENV CGO_ENABLED=${plan.cgo ? 1 : 0}`,
    "COPY go.mod go.sum* ./",
    "RUN go mod download",
    "COPY . .",
    "RUN mkdir -p /out",
    build,
    "",
    ...binaryRuntime(opts.port),
    // The source tree stays beside the binary for templates and static files read at run time.
    "COPY --from=build /src /app",
    "COPY --from=build /out/ /usr/local/bin/",
    cmd(opts.startCommand || stack.startCommand),
  ];
}

function rust(stack: DetectedStack, opts: DockerfileOptions): string[] {
  const bin = stack.plan.binName || "";
  const build = opts.buildCommand
    ? runUser(opts.buildCommand)
    : `RUN if [ -f Cargo.lock ]; then cargo build --release --locked; else cargo build --release; fi`;
  return [
    "FROM rust:1-bookworm AS build",
    "WORKDIR /src",
    ...caBlock(opts),
    "COPY . .",
    build,
    `RUN set -e; mkdir -p /out; b=${shArg(bin)}; if [ -n "$b" ] && [ -x "target/release/$b" ]; then cp "target/release/$b" /out/app; else f=$(find target/release -maxdepth 1 -type f -perm -u+x | head -n 1); if [ -z "$f" ]; then echo "cargo build produced no binary in target/release" >&2; exit 1; fi; cp "$f" /out/app; fi`,
    "",
    ...binaryRuntime(opts.port, "ROCKET_ADDRESS=0.0.0.0"),
    "COPY --from=build /out/app /usr/local/bin/app",
    cmd(opts.startCommand || stack.startCommand),
  ];
}

// ─── PHP ─────────────────────────────────────────────────────────────────────

function php(stack: DetectedStack, opts: DockerfileOptions): string[] {
  const plan = stack.plan;
  const docRoot = plan.docRoot && plan.docRoot !== "." ? `/var/www/html/${plan.docRoot}` : "/var/www/html";
  const lines: string[] = [];
  if (plan.composer) {
    // The composer image has git/unzip, so dependencies install without apt in the runtime image.
    lines.push(
      "FROM composer:2 AS vendor",
      "WORKDIR /app",
      ...caBlock(opts),
      "COPY composer.json composer.lock* ./",
      "RUN composer install --no-dev --no-scripts --no-autoloader --prefer-dist --no-interaction --no-progress --ignore-platform-reqs",
      ""
    );
  }
  const apacheConf = ["<Directory ${APACHE_DOCUMENT_ROOT}>", "  Options -Indexes +FollowSymLinks", "  AllowOverride All", "  Require all granted", "</Directory>"];
  lines.push(
    "FROM php:8.3-apache",
    `ENV APACHE_DOCUMENT_ROOT=${docRoot}`,
    // Apache expands ${PORT} and ${APACHE_DOCUMENT_ROOT} from the environment at start-up.
    `RUN set -e; sed -ri 's!/var/www/html!\${APACHE_DOCUMENT_ROOT}!g' /etc/apache2/sites-available/*.conf; ` +
      `sed -ri 's/^Listen 80$/Listen \${PORT}/' /etc/apache2/ports.conf; ` +
      `sed -ri 's/<VirtualHost \\*:80>/<VirtualHost *:\${PORT}>/' /etc/apache2/sites-available/000-default.conf; ` +
      `printf '%s\\n' ${apacheConf.map(shArg).join(" ")} > /etc/apache2/conf-available/syncbay.conf; ` +
      `echo 'ServerName localhost' > /etc/apache2/conf-available/servername.conf; ` +
      `a2enconf syncbay servername >/dev/null; a2enmod rewrite headers >/dev/null`
  );
  if (plan.laravel) lines.push("RUN docker-php-ext-install pdo_mysql bcmath opcache >/dev/null");
  lines.push("WORKDIR /var/www/html", "COPY . .");
  if (plan.composer) {
    lines.push(
      "COPY --from=vendor /app/vendor ./vendor",
      "COPY --from=vendor /usr/bin/composer /usr/bin/composer",
      `RUN composer dump-autoload --optimize --no-dev --no-interaction --no-scripts${plan.laravel ? " && (php artisan package:discover --ansi || true)" : ""}`
    );
  }
  if (plan.laravel) lines.push("RUN mkdir -p storage bootstrap/cache && chown -R www-data:www-data storage bootstrap/cache");
  if (opts.buildCommand) lines.push(runUser(opts.buildCommand));
  lines.push(...portEnv(opts.port), cmd(opts.startCommand || stack.startCommand));
  return lines;
}

// ─── JAVA / RUBY / DENO ──────────────────────────────────────────────────────

function java(stack: DetectedStack, opts: DockerfileOptions): string[] {
  const plan = stack.plan;
  const maven = plan.javaTool !== "gradle";
  const image = maven ? "maven:3.9-eclipse-temurin-21" : "gradle:8-jdk21";
  const defaultBuild = maven
    ? `if [ -f mvnw ]; then chmod +x mvnw && ./mvnw -B -DskipTests package; else mvn -B -DskipTests package; fi`
    : `if [ -f gradlew ]; then chmod +x gradlew && G=./gradlew; else G=gradle; fi; $G --no-daemon -x test bootJar || $G --no-daemon -x test build`;
  return [
    `FROM ${image} AS build`,
    "WORKDIR /src",
    ...caBlock(opts, true),
    "COPY . .",
    opts.buildCommand ? `RUN ["/bin/sh", "-c", ${JSON.stringify(JVM_PROXY + opts.buildCommand)}]` : `RUN ${JVM_PROXY}${defaultBuild}`,
    `RUN set -e; mkdir -p /out; jar=$(ls -S target/*.jar build/libs/*.jar 2>/dev/null | grep -v -E '(-plain|-sources|-javadoc|/original-)' | head -n 1); if [ -z "$jar" ]; then echo "The build produced no jar in target/ or build/libs/" >&2; exit 1; fi; cp "$jar" /out/app.jar`,
    "",
    "FROM eclipse-temurin:21-jre",
    "WORKDIR /app",
    "COPY --from=build /out/app.jar /app/app.jar",
    ...portEnv(opts.port, `JAVA_TOOL_OPTIONS="-XX:MaxRAMPercentage=75"`),
    cmd(opts.startCommand || stack.startCommand),
  ];
}

function ruby(stack: DetectedStack, opts: DockerfileOptions): string[] {
  const plan = stack.plan;
  const version = plan.rubyVersion || "3.3";
  const bundleEnv = "BUNDLE_WITHOUT=development:test BUNDLE_PATH=/usr/local/bundle";
  const lines = [
    // The full image has the compilers native gems need; the runtime image does not.
    `FROM ruby:${version} AS build`,
    "WORKDIR /app",
    ...caBlock(opts),
    `ENV ${bundleEnv}`,
    "COPY Gemfile Gemfile.lock* ./",
    "RUN bundle install --jobs 4",
    "COPY . .",
  ];
  if (plan.rails) lines.push(`RUN SECRET_KEY_BASE_DUMMY=1 RAILS_ENV=production bundle exec rails assets:precompile >/dev/null 2>&1 && echo "assets precompiled" || echo "assets:precompile skipped"`);
  if (opts.buildCommand) lines.push(runUser(opts.buildCommand));
  lines.push("", `FROM ruby:${version}-slim`);
  if (plan.aptPackages?.length) lines.push(`RUN apt-get update && apt-get install -y --no-install-recommends ${plan.aptPackages.join(" ")} && rm -rf /var/lib/apt/lists/*`);
  lines.push(
    "WORKDIR /app",
    `ENV ${bundleEnv} RAILS_ENV=production RACK_ENV=production RAILS_LOG_TO_STDOUT=1 RAILS_SERVE_STATIC_FILES=1`,
    "COPY --from=build /usr/local/bundle /usr/local/bundle",
    "COPY --from=build /app /app",
    ...portEnv(opts.port),
    cmd(opts.startCommand || stack.startCommand)
  );
  return lines;
}

function deno(stack: DetectedStack, opts: DockerfileOptions): string[] {
  const entry = stack.plan.denoEntry;
  return [
    "FROM denoland/deno:latest",
    "WORKDIR /app",
    ...caBlock(opts),
    "COPY . .",
    entry ? `RUN deno cache ${shArg(entry)}` : "RUN deno install || true",
    ...(opts.buildCommand ? [runUser(opts.buildCommand)] : []),
    ...portEnv(opts.port),
    cmd(opts.startCommand || stack.startCommand),
  ];
}

// ─── ENTRY POINTS ────────────────────────────────────────────────────────────

/** Dockerfile text for a detected stack. User build/start commands replace the stack defaults. */
export function generateDockerfile(stack: DetectedStack, opts: DockerfileOptions): string {
  let body: string[];
  switch (stack.id) {
    case "node":
    case "bun":
      body = nodeServer(stack, opts);
      break;
    case "static":
      // A custom start command means the user serves the site with their own Node server.
      body = opts.startCommand ? nodeServer(stack, opts) : staticSite(stack, opts);
      break;
    case "python":
      body = python(stack, opts);
      break;
    case "go":
      body = go(stack, opts);
      break;
    case "rust":
      body = rust(stack, opts);
      break;
    case "php":
      body = php(stack, opts);
      break;
    case "java":
      body = java(stack, opts);
      break;
    case "ruby":
      body = ruby(stack, opts);
      break;
    case "deno":
      body = deno(stack, opts);
      break;
  }
  return withBuildArgs([...header(stack), ...body], opts.buildArgs).concat("").join("\n");
}

const BUILD_ARG_NAME = /^[A-Za-z_][A-Za-z0-9_]*$/;
/** Set by the platform at run time; never a build argument. */
const RUNTIME_ONLY = new Set(["PORT", "HOST", "HOSTNAME", "HTTP_PORT", "SERVER_PORT"]);

/** Final-stage bases that only run the built artefact (no install or build steps happen there). */
const RUNTIME_ONLY_BASE = /^FROM\s+(nginx:|debian:|eclipse-temurin:\S+-jre|ruby:\S+-slim)/;

/**
 * Declares the service's variables as `ARG`s in every stage that installs or builds: all stages,
 * except a last stage on a pure runtime base (nginx, debian-slim, a JRE, ruby-slim), which gets
 * the values from `docker run -e` instead so they stay out of its layers. (PHP's final stage, for
 * example, runs Composer and the service's build command, so it gets them.)
 */
function withBuildArgs(lines: string[], names: string[] = []): string[] {
  const args = [...new Set(names)].filter((n) => BUILD_ARG_NAME.test(n) && !RUNTIME_ONLY.has(n)).sort();
  if (args.length === 0) return lines;
  const fromIdx = lines.map((l, i) => (/^FROM\s/.test(l) ? i : -1)).filter((i) => i >= 0);
  const last = fromIdx[fromIdx.length - 1];
  const stages = fromIdx.length > 1 && RUNTIME_ONLY_BASE.test(lines[last]) ? fromIdx.slice(0, -1) : fromIdx;
  const out: string[] = [];
  lines.forEach((line, i) => {
    out.push(line);
    if (stages.includes(i)) out.push(...args.map((a) => `ARG ${a}`));
  });
  return out;
}

