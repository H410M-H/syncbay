/**
 * Content for `Dockerfile.syncbay.dockerignore`. A user's `.dockerignore` is kept as it is (only
 * the build CA file is re-included); otherwise sensible defaults for the stack are used.
 */
export function generateDockerignore(stack: DetectedStack, userIgnore?: string | null): string {
  const keepCa = `!${BUILD_CA_FILE}`;
  if (userIgnore && userIgnore.trim()) {
    return `${userIgnore.replace(/\s+$/, "")}\n# Added by Syncbay: the build CA must reach the build\n${keepCa}\n`;
  }
  return [`# Generated by Syncbay for ${stack.label}`, ...IGNORE_COMMON, ...IGNORE_BY_STACK[stack.id], keepCa, ""].join("\n");
}
